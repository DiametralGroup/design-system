/* ============================================================================
   build-migration-guide.mjs — turn docs/migration/renames.json into the two
   places a rename has to appear:

     docs/migration/from-0.11.md          the 0.11 → 1.0 migration guide
     docs/migration/changelog-fragment.md the block to paste into CHANGELOG.md

   Both are GENERATED. Edit renames.json, not the output. Batches record their
   renames as rows; nobody hand-writes the guide, so it cannot drift from what
   actually shipped.
   ============================================================================ */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const out = join(root, "docs", "migration");
const { renames } = JSON.parse(
  readFileSync(join(out, "renames.json"), "utf8"),
);

const KINDS = {
  component: "Components",
  export: "Exports",
  class: "Classes",
  token: "Tokens",
  path: "Paths",
};
const byKind = (k) => renames.filter((r) => r.kind === k);
const arrow = (r) => (r.to === null ? "_removed_" : `\`${r.to}\``);

const HEADER = "<!-- GENERATED by scripts/build-migration-guide.mjs. Edit docs/migration/renames.json. -->";

/* -- the guide ------------------------------------------------------------ */

const sections = Object.entries(KINDS).flatMap(([kind, heading]) => {
  const rows = byKind(kind);
  if (!rows.length) return [];
  return [
    `### ${heading}`,
    "",
    "| 0.11 | 1.0 | batch | notes |",
    "| --- | --- | --- | --- |",
    ...rows.map(
      (r) => `| \`${r.from}\` | ${arrow(r)} | ${r.batch} | ${r.note ?? ""} |`,
    ),
    "",
  ];
});

writeFileSync(
  join(out, "from-0.11.md"),
  [
    HEADER,
    "",
    "# Migrating from 0.11 to 1.0",
    "",
    renames.length
      ? `The v1 absorption renames ${renames.length} consumer-visible thing(s). Everything else is additive.`
      : "No renames recorded yet. The v1 absorption is additive so far — nothing a 0.11 consumer imports, targets or references has changed name.",
    "",
    ...sections,
  ].join("\n"),
);

/* -- the changelog fragment ----------------------------------------------- */

writeFileSync(
  join(out, "changelog-fragment.md"),
  [
    HEADER,
    "",
    ...(renames.length
      ? [
          "### Renamed",
          "",
          ...renames.map(
            (r) =>
              `- \`${r.from}\` → ${arrow(r)}${r.note ? ` — ${r.note}` : ""} (batch ${r.batch})`,
          ),
        ]
      : ["_No renames recorded._"]),
    "",
  ].join("\n"),
);

console.log(
  `build-migration-guide: ${renames.length} rename(s) -> docs/migration/from-0.11.md, docs/migration/changelog-fragment.md`,
);
